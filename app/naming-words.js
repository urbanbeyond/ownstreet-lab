const SUFFIXES = ["스러움", "스러운", "스럽다", "하다", "했던", "해요", "함", "한", "색", "이야", "야", "요"];

function variants(word) {
  const w = word.trim().toLowerCase().replace(/\s+/g, "");
  const out = [w];
  for (const s of SUFFIXES) if (w.length > s.length + 0 && w.endsWith(s)) out.push(w.slice(0, -s.length));
  return out.filter(Boolean);
}

// 단어에 맞는 이름 예시들. 없으면 []
export function namingIdeas(word) {
  const vs = variants(word);
  for (const v of vs) {
    for (const [keys, names] of NAMING_WORDS) if (keys.some((k) => k.toLowerCase() === v)) return names;
  }
  let best = null;
  let bestLen = 1;
  for (const [keys, names] of NAMING_WORDS) {
    for (const k of keys) {
      const kk = k.toLowerCase();
      if (kk.length > bestLen && vs[0].includes(kk)) { best = names; bestLen = kk.length; }
    }
  }
  return best || [];
}
